def tab_dose():
    rows = []
    # eps -> (pattern, seeds)；1.0 用 P1（5 seeds），0.99/0.95 用 P9，0.9 用 P7
    spec = [(1.0, "P1_main_high_L{L}_s{s}", SEEDS5),
            (0.99, "P9_eps0.99_L{L}_s{s}", SEEDS3),
            (0.95, "P9_eps0.95_L{L}_s{s}", SEEDS3),
            (0.9, "P7_dose_eps0.9_L{L}_s{s}", SEEDS3),
            (0.0, "P5_diag_eps0_s{s}", SEEDS4)]
    for eps, pat, seeds in spec:
        for Lv in (250, 4000):
            if eps == 0.0:
                ids = [pat.format(s=s) for s in seeds]      # P5 只有 L=4000
                if Lv != 4000:
                    continue
            else:
                ids = [pat.format(L=Lv, s=s) for s in seeds]
            eb = _vals(ids, lambda r: L.end_b(r).get("acc_old_probe"))
            eh = _vals(ids, lambda r: L.end_b(r).get("acc_old_cur"))
            w2 = _vals(ids, lambda r: L.end_b(r).get("W2_norm"))
            acc = _vals(ids, lambda r: L.final_c(r).get("new_task_acc"))
            if not eb:
                continue
            rows.append(f"{eps:.2g} & {Lv} & {len(eb)} & {_pm(eh)} & {_pm(eb)} & "
                        f"{_pm(w2)} & {_pm(acc)} \\\\")
    tex = (
        "% auto-generated by analysis/make_tables.py\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Dose--response: how much class information the exposure target "
        "still carries ($\\varepsilon=0$: continued CE; $\\varepsilon=1.0$: uniform) "
        "controls both head release and feature damage.}\n"
        "\\label{tab:dose}\n\\small\n"
        "\\begin{tabular}{llrccccc}\n\\toprule\n"
        "$\\varepsilon$ & $L$ & $n$ & head@endB & probe@endB & "
        "$\\|W_2\\|_{\\mathrm{endB}}$ & new acc \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (OUT / "tab_dose.tex").write_text(tex, encoding="utf-8")
    print("-> tables/tab_dose.tex")


