def tab_resources():
    ids = [r["run_id"] for r in L.grid_runs() if r["block"].startswith("P")
           or r["block"] == "P7-dose"]
    walls, rss, gpu = [], [], []
    for rid in ids:
        s = L.summary(rid)
        if s.get("status") != "succeeded":
            continue
        if s.get("wall_s"):
            walls.append(s["wall_s"])
        if s.get("rss_peak_mb") and s["rss_peak_mb"] == s["rss_peak_mb"]:
            rss.append(s["rss_peak_mb"])
        if s.get("gpu_peak_mb"):
            gpu.append(s["gpu_peak_mb"])
    tex = (
        "% auto-generated by analysis/make_tables.py\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Measured resources over all formal runs (RTX 5060 Laptop, 8.5\\,GB).}\n"
        "\\label{tab:resources}\n\\small\n"
        "\\begin{tabular}{lcc}\n\\toprule\nmetric & value & unit \\\\\n\\midrule\n"
        f"runs measured & {len(walls)} & -- \\\\\n"
        f"wall per run (mean) & {statistics.mean(walls) if walls else float('nan'):.1f} & s \\\\\n"
        f"wall per run (max) & {max(walls) if walls else float('nan'):.1f} & s \\\\\n"
        f"peak RSS (max) & {max(rss) if rss else float('nan'):.0f} & MB \\\\\n"
        f"peak GPU mem (max) & {max(gpu) if gpu else float('nan'):.0f} & MB \\\\\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (OUT / "tab_resources.tex").write_text(tex, encoding="utf-8")
    print("-> tables/tab_resources.tex")


