def tab_det():
    """确定性核复现：同配置两份 run 的逐位一致性 + 终态 L 效应。"""
    rows = []
    for s in (42, 123):
        for Lv in (0, 250, 4000):
            a = L.metrics(f"P10_det_L{Lv}_s{s}_a")
            b = L.metrics(f"P10_det_L{Lv}_s{s}_b")
            if not a or not b or len(a) != len(b):
                rows.append(f"{s} & {Lv} & - & - \\\\")
                continue
            d = max(abs(ra.get(k, 0) - rb.get(k, 0)) for ra, rb in zip(a, b)
                    for k in ra if isinstance(ra.get(k), float))
            rows.append(f"{s} & {Lv} & {len(a)} & {d:.1e} \\\\")
    tex = (
        "% auto-generated by analysis/make_tables.py\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Deterministic-kernel replication (P10): two independent runs with "
        "identical configuration produce bitwise-identical metric streams "
        "(max $|\\Delta|$ over all rows), so terminal differences are no longer "
        "contaminated by process-level rerun noise.}\n"
        "\\label{tab:det}\n\\small\n"
        "\\begin{tabular}{rrrc}\n\\toprule\n"
        "seed & $L$ & rows & max $|\\Delta|$ \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (OUT / "tab_det.tex").write_text(tex, encoding="utf-8")
    print("-> tables/tab_det.tex")


