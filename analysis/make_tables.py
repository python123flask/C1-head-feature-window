SEEDS5 = [42, 123, 456, 789, 1024]
SEEDS4 = [42, 123, 456, 789]
SEEDS3 = [42, 123, 456]


def _vals(ids, key_getter):
    out = []
    for rid in ids:
        if not L.finished_ok(rid):
            continue
        v = key_getter(rid)
        if v is not None:
            out.append(v)
    return out


def _pm(vals):
    if not vals:
        return "--"
    return f"{statistics.mean(vals):.3f} $\\pm$ {statistics.pstdev(vals):.3f}"


def tab_main():
    rows = []
    for shared, label in (("high", "high"), ("low", "low")):
        for Lv in (0, 250, 1000, 4000):
            ids = [f"P1_main_{shared}_L{Lv}_s{s}" for s in SEEDS5]
            acc = _vals(ids, lambda r: L.final_c(r).get("new_task_acc"))
            nll = _vals(ids, lambda r: L.final_c(r).get("new_task_NLL"))
            spd = _vals(ids, lambda r: L.adaptation_speed(r, 1000).get("acc_mean"))
            eb = _vals(ids, lambda r: L.end_b(r).get("acc_old_probe"))
            eh = _vals(ids, lambda r: L.end_b(r).get("acc_old_cur"))
            a2 = 0
            for rid in ids:
                hits = [x for x in L.phase_rows(rid, "B")
                        if x.get("acc_old_cur", 1) <= 0.5 and x.get("acc_old_probe", 0) >= 0.7]
                a2 += bool(hits)
            rows.append(f"{label} & {Lv} & {len(acc)} & {_pm(acc)} & {_pm(nll)} & "
                        f"{_pm(spd)} & {_pm(eh)} & {_pm(eb)} & {a2} \\\\")
    body = "\n".join(rows)
    tex = (
        "% auto-generated by analysis/make_tables.py\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\caption{Main sweep: terminal new-task performance and head/feature state after "
        "exposure length $L$ (mean$\\pm$std over 5 seeds). "
        "$\\mathrm{A2}$ counts seeds with at least one evaluation point satisfying "
        "head acc $\\le 0.50$ and probe acc $\\ge 0.70$.}\n"
        "\\label{tab:main}\n\\small\n"
        "\\begin{tabular}{llrcccccc}\n\\toprule\n"
        "share & $L$ & $n$ & new acc & new NLL & speed$_{1000}$ & "
        "head@endB & probe@endB & A2 \\\\\n\\midrule\n"
        f"{body}"
        "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (OUT / "tab_main.tex").write_text(tex, encoding="utf-8")
    print("-> tables/tab_main.tex")


